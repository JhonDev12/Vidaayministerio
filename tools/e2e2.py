from playwright.sync_api import sync_playwright
S="/tmp/claude-0/-home-claude/05e824d9-50dc-531c-8567-c5912e50f409/scratchpad/shots/"
with sync_playwright() as p:
    b = p.chromium.launch()
    ctx = b.new_context(viewport={'width':390,'height':844}, device_scale_factor=2, accept_downloads=True, locale='es-CO', timezone_id='America/Bogota')
    page = ctx.new_page()
    logs=[]
    page.on('console', lambda m: logs.append(m.type+': '+m.text))
    page.on('pageerror', lambda e: logs.append('PAGEERROR '+str(e)))
    page.goto('http://localhost:8765/index.html#/semana/2026-11-30')
    page.wait_for_timeout(700)
    page.screenshot(path=S+'m_semana2.png')
    # abrir selector de la parte sin asignar (7)
    page.click('[data-slot="p6.0"]')
    page.wait_for_timeout(400)
    page.screenshot(path=S+'m_picker.png')
    page.keyboard.press('Escape')
    page.click('text=Vista previa >> nth=0')
    page.wait_for_timeout(500)
    page.screenshot(path=S+'m_preview.png')
    page.keyboard.press('Escape')
    page.goto('http://localhost:8765/index.html#/personas')
    page.wait_for_timeout(500)
    page.screenshot(path=S+'m_personas.png')
    page.goto('http://localhost:8765/index.html#/descargar')
    page.wait_for_timeout(600)
    page.screenshot(path=S+'m_desc.png', full_page=True)
    # desktop
    ctx2 = b.new_context(viewport={'width':1280,'height':800}, locale='es-CO', timezone_id='America/Bogota')
    pg = ctx2.new_page(); pg.on('pageerror', lambda e: logs.append('PAGEERROR '+str(e)))
    pg.goto('http://localhost:8765/index.html'); pg.wait_for_timeout(600)
    pg.screenshot(path=S+'d_programa.png')
    print('\n'.join(logs))
    b.close()
